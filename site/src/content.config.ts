import { defineCollection } from "astro:content";
import { glob } from "astro/loaders";
import { z } from "astro/zod";
import { scienceProjectIds } from "./data/scienceProjects";
import { personalCategoryIds } from "./data/personal";

const baseFields = {
  title: z.string(),
  description: z.string(),
  date: z.coerce.date(),
  updated: z.coerce.date().optional(),
  tags: z.array(z.string()).default([]),
  featured: z.boolean().default(false),
  draft: z.boolean().default(false),
  socialImage: z
    .object({
      src: z.string(),
      alt: z.string(),
      width: z.number().int().positive(),
      height: z.number().int().positive(),
    })
    .optional(),
  practice: z
    .array(
      z.object({
        question: z.string(),
        hint: z.string(),
        answer: z.string(),
        topic: z.string().optional(),
      })
    )
    .optional(),
};

const systemDesign = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/system-design" }),
  schema: z.object({
    ...baseFields,
    topic: z.string().optional(),
    level: z.array(z.string()).optional(),
    companies: z.array(z.string()).optional(),
  }),
});

const coding = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/coding" }),
  schema: z.object({
    ...baseFields,
    difficulty: z.enum(["easy", "medium", "hard"]).optional(),
    patterns: z.array(z.string()).optional(),
    languages: z.array(z.string()).optional(),
    companies: z.array(z.string()).optional(),
  }),
});

const interviews = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/interviews" }),
  schema: z.object({
    ...baseFields,
    company: z.string().optional(),
    level: z.string().optional(),
    rounds: z.array(z.string()).optional(),
    sample: z.boolean().default(false),
  }),
});

const fieldNotes = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/field-notes" }),
  schema: z.object({
    ...baseFields,
    topic: z.string().trim().min(1),
  }),
});

const science = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/science" }),
  schema: z.object({
    ...baseFields,
    project: z.enum(scienceProjectIds),
    lang: z.enum(["en", "zh-CN"]).default("en"),
    // Latin-script artwork avoids missing CJK fonts on the deployment runner.
    socialTitle: z.string().optional(),
    socialDescription: z.string().optional(),
  }),
});

const ai = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/ai" }),
  schema: z.object({
    ...baseFields,
    topic: z.string().trim().min(1),
    order: z.number().int().positive(),
    lang: z.enum(["en", "zh-CN"]).default("en"),
    // English card text avoids depending on CJK fonts on the build runner.
    socialTitle: z.string().trim().min(1),
    socialDescription: z.string().trim().min(1),
  }),
});

const personal = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/personal" }),
  schema: z.object({
    ...baseFields,
    category: z.enum(personalCategoryIds),
    topic: z.string().trim().min(1).optional(),
    lang: z.enum(["en", "zh-CN"]).default("en"),
    // Latin-script artwork avoids missing CJK fonts on the deployment runner.
    socialTitle: z.string().optional(),
    socialDescription: z.string().optional(),
  }),
});

// Optional second-language versions of articles in any section. The file path
// mirrors the article it translates: translations/<section>/<article id>.md,
// e.g. translations/field-notes/tcp-three-way-handshake.md. Science and
// Personal Interest articles use their bare article id, without the project or
// category folder. Daily and weekly digests use eng-digest/<date> and
// eng-digest/weekly/<week>.
const translations = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/translations" }),
  schema: z.object({
    title: z.string(),
    description: z.string(),
    socialTitle: z.string().optional(),
    socialDescription: z.string().optional(),
    // The language of this file. Most articles are written in English, so a
    // translation defaults to Simplified Chinese; set "en" for the English
    // version of an article originally written in Chinese.
    lang: z.enum(["en", "zh-CN"]).default("zh-CN"),
    draft: z.boolean().default(false),
  }),
});

// Generated by site/scripts/import-digests.mjs from ../digests/digest-*.md.
// Never hand-authored; the directory is gitignored.
const generatedDigests = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/generated-digests" }),
  schema: z.object({
    title: z.string(),
    date: z.coerce.date(),
    generated: z.boolean().default(true),
    articleCount: z.number().optional(),
    sourceCount: z.number().optional(),
    sources: z.array(z.string()).optional(),
  }),
});

const generatedWeekly = defineCollection({
  loader: glob({ pattern: "**/*.{md,mdx}", base: "./src/content/generated-weekly" }),
  schema: z.object({
    title: z.string(),
    date: z.coerce.date(),
    weekStart: z.coerce.date(),
    weekEnd: z.coerce.date(),
    digestCount: z.number(),
    articleCount: z.number(),
    sourceCount: z.number(),
    complete: z.boolean(),
    topTopics: z.array(z.object({ name: z.string(), count: z.number() })),
    topSources: z.array(z.object({ name: z.string(), count: z.number() })),
    representativeArticles: z.array(
      z.object({
        title: z.string(),
        url: z.string(),
        source: z.string(),
        topic: z.string(),
        summary: z.string(),
      })
    ),
  }),
});

export const collections = {
  "system-design": systemDesign,
  coding,
  interviews,
  "field-notes": fieldNotes,
  science,
  ai,
  personal,
  translations,
  "generated-digests": generatedDigests,
  "generated-weekly": generatedWeekly,
};
